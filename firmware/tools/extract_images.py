#!/usr/bin/env python3
"""Extract the display images of firmware 1.4.00 from record 11.
Image table at load X:43A1B3 (run X:7EBCAA): entries {width, height, data pointer (run address)}.
The first 4 entries are font strips; images follow. Run address = load address + 0x3B1AF7.
Pixel data: 1 bpp, stored in 24-row bands: band 0 (rows 0-23) for all columns left to right, then band 1, ...; LSB = top row of the band.
usage: extract_images.py [outdir]  -> PNGs + index.json + contact sheet"""
import sys, os, json, zlib, struct
OUT = sys.argv[1] if len(sys.argv) > 1 else 'graphics/images-1.4.00'
b = open('data/records-1.4.00/r11_X_43a180.bin', 'rb').read()
W = [int.from_bytes(b[i:i+3], 'big') for i in range(0, len(b) - 2, 3)]
BASE, RUN = 0x43a180, 0x3B1AF7
TABLE = 0x43a1b3
w = lambda a: W[a - BASE]
def png(path, width, height, rows, scale=1):
    rows = [[p for p in r for _ in range(scale)] for r in rows for _ in range(scale)]
    raw = b''.join(b'\x00' + bytes(r) for r in rows)
    ch = lambda t, d: struct.pack('>I', len(d)) + t + d + struct.pack('>I', zlib.crc32(t + d) & 0xffffffff)
    open(path, 'wb').write(b'\x89PNG\r\n\x1a\n' + ch(b'IHDR', struct.pack('>IIBBBBB', width*scale, height*scale, 8, 0, 0, 0, 0)) + ch(b'IDAT', zlib.compress(raw, 9)) + ch(b'IEND', b''))
def pixels(e):
    wd, ht, ptr = e; n = (ht + 23) // 24; a = ptr - RUN
    return [[0 if (w(a + (y//24)*wd + x) >> (y % 24)) & 1 else 255 for x in range(wd)] for y in range(ht)]
os.makedirs(OUT, exist_ok=True)
ents = []
a = TABLE
while True:
    wd, ht, ptr = w(a), w(a+1), w(a+2)
    if not (0 < wd <= 0x1000 and 0 < ht <= 128 and 0x7e0000 <= ptr < 0x800000): break
    ents.append((wd, ht, ptr)); a += 3
idx = []
for i, e in enumerate(ents):
    if i < 4: continue      # font strips
    png(os.path.join(OUT, f'img{i:03d}.png'), e[0], e[1], pixels(e), 2)
    idx.append({"index": i, "table_entry_run": f"0x{TABLE + 3*i + RUN:06X}", "width": e[0], "height": e[1], "ptr": f"0x{e[2]:06X}"})
json.dump(idx, open(os.path.join(OUT, 'index.json'), 'w'), indent=1)
print(len(ents), 'table entries,', len(idx), 'images ->', OUT)
# contact sheet with index numbers (3x5 digits)
D = {'0':'111101101101111','1':'010110010010111','2':'111001111100111','3':'111001111001111','4':'101101111001001','5':'111100111001111','6':'111100111101111','7':'111001001001001','8':'111101111101111','9':'111101111001111'}
CW, CH, COLS = 132, 74, 8
imgs = [(i, e) for i, e in enumerate(ents) if i >= 4]
rows_n = (len(imgs) + COLS - 1) // COLS
sheet = [[200]*(CW*COLS) for _ in range(CH*rows_n)]
for k, (i, e) in enumerate(imgs):
    ox, oy = (k % COLS)*CW + 2, (k // COLS)*CH + 9
    for x0, ch in enumerate(str(i)):
        for p, bit in enumerate(D[ch]):
            if bit == '1': sheet[(k//COLS)*CH + 2 + p//3][ox + x0*4 + p%3] = 0
    px = pixels(e)
    for y in range(min(e[1], CH-10)):
        for x in range(min(e[0], CW-4)): sheet[oy+y][ox+x] = px[y][x]
png(os.path.join(OUT, 'contact-sheet.png'), CW*COLS, CH*rows_n, sheet, 1)

# --js: write tools/pa-images.js (images used by the FX pages + Error, as transparent PNG data URIs) and print the
# per-page image lists. Style image sets: table at load X:439A1D (run X:7EBAC2) = 13 x {list ptr (run = load + 0x3B20A5), count};
# entries are image-table addresses X:3111 + 3*index (the table is copied to X:3111 at boot by the C init table).
# func_446c06: set = [Vocal FX sub-page 0-7] or 8 + [Guitar FX sub-page 0-4]; image = set[value of the page's first cell].
if '--js' in sys.argv:
    import base64
    b9 = open('data/records-1.4.00/r09_X_42c560.bin', 'rb').read()
    W9 = [int.from_bytes(b9[i:i+3], 'big') for i in range(0, len(b9) - 2, 3)]
    w9 = lambda a: W9[a - 0x42c560]
    SETS = [[(w9(w9(0x439a1d + 2*k) - 0x3B20A5 + j) - 0x3111) // 3 for j in range(w9(0x439a1e + 2*k))] for k in range(13)]
    def pngga(e):
        wd, ht, ptr = e; a = ptr - RUN
        rows = [b''.join(b'\xff\xff' if (w(a + (y//24)*wd + x) >> (y % 24)) & 1 else b'\x00\x00' for x in range(wd)) for y in range(ht)]
        ch = lambda t, d: struct.pack('>I', len(d)) + t + d + struct.pack('>I', zlib.crc32(t + d) & 0xffffffff)
        return b'\x89PNG\r\n\x1a\n' + ch(b'IHDR', struct.pack('>IIBBBBB', wd, ht, 8, 4, 0, 0, 0)) + ch(b'IDAT', zlib.compress(b''.join(b'\x00' + r for r in rows), 9)) + ch(b'IEND', b'')
    used = sorted({i for st in SETS for i in st} | {39})
    L = ['// Play Acoustic Remote: display pictures from firmware 1.4.00 (generated by tools/extract_images.py --js; not meant for hand editing).',
         '// Key = image number in the firmware image table (see graphics/images-1.4.00/contact-sheet.png). Lit pixels are opaque, the rest transparent.',
         'window.PA_IMAGES = {'] + [f'  "{i}": "data:image/png;base64,{base64.b64encode(pngga(ents[i])).decode()}",' for i in used]
    L[-1] = L[-1].rstrip(','); L.append('};')
    open('tools/pa-images.js', 'w').write('\n'.join(L) + '\n')
    for k, st in enumerate(SETS): print('set', k, st)
